'use strict';
const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
const { chromium } = require(process.argv[2] || 'playwright');
const root = path.resolve(__dirname, '..');
const output = path.resolve(process.argv[4] || path.join(root, '../../output/playwright/sortable-settings-20261113'));
fs.mkdirSync(output, { recursive: true });
const source = fs.readFileSync(path.join(root, 'renderer/layout-custom.js'), 'utf8');
const css = fs.readFileSync(path.join(root, 'assets/layout-custom.css'), 'utf8');
const icon = id => `<svg viewBox="0 0 24 24" aria-label="original-${id}"><path d="M${id} 4h12v14H${id}z"/></svg>`;
const menu = (name, id, extra = '') => `<div class="q-context-menu-item ${extra}"><span class="q-context-menu-item__icon">${icon(id)}</span><span class="q-context-menu-item__text">${name}</span></div>`;
const fixture = `<!doctype html><body data-liuli-scope="main"><div class="chat-input-area"><div class="chat-func-bar">${['表情', '图片', '文件', '截图'].map((name, i) => `<div class="bar-icon"><div class="icon-item" aria-label="${name}">${icon(i + 2)}</div></div>`).join('')}</div></div><div class="sidebar__nav"><div class="nav-item" aria-label="消息">${icon(3)}</div><div class="nav-item" aria-label="联系人">${icon(4)}</div></div><div class="sidebar__menu"><div class="func-menu__item" aria-label="更多">${icon(5)}</div></div><div class="q-context-menu aio-right-click-menu">${menu('复制', 1) + menu('转发', 2) + menu('复读', 3, 'qe-repeat-item') + menu('收藏', 4)}</div></body>`;
const config = page => page.evaluate(() => JSON.parse(localStorage.getItem('liuli-layout')));
const names = async (page, kind) => page.locator(`.liuli-lo-list[data-icon-kind="${kind}"] .liuli-lo-row`).evaluateAll(rows => rows.map(row => row.dataset.orderKey));
(async () => {
  const browser = await chromium.launch({ headless: true, ...(process.argv[3] ? { executablePath: process.argv[3] } : {}) });
  const report = { scope: 'Production layout module in two same-origin Chromium windows; no live QQ configuration writes', checks: [] };
  try {
    const context = await browser.newContext({ viewport: { width: 900, height: 1500 } });
    await context.route('http://liuli.test/**', route => route.fulfill({ contentType: 'text/html', body: '<!doctype html><body></body>' }));
    const main = await context.newPage();
    await main.goto('http://liuli.test/main');
    await main.setContent(fixture);
    await main.evaluate(() => {
      localStorage.setItem('liuli-layout', JSON.stringify({ inputLayout: 'float', barPinned: 2, barOrder: ['表情', '图片', '文件', '截图'], menuOrder: ['复制', '转发', '复读', '收藏'] }));
      window.originalSvg = document.querySelector('.bar-icon svg');
      window.nativeClicks = 0;
      document.querySelector('.bar-icon:last-child svg').innerHTML = '<use xlink:href="/_upper_/resource/icons/screenshot.svg#screenshot"/>';
      document.querySelector('.q-context-menu-item').addEventListener('click', () => window.nativeClicks++);
    });
    await main.addScriptTag({ content: source });
    await main.evaluate(() => LiuliLayout.installLayout());
    const settings = await context.newPage();
    await settings.goto('http://liuli.test/setting');
    await settings.setContent('<!doctype html><style>body{font:14px sans-serif;margin:24px;--ll-on-glass-rgb:40,40,60;--ll-on-glass:#28283c;--ll-on-glass-2:#515169;--ll-brand:#6350a5;--ll-brand-rgb:99,80,165}.liuli-panel__group{margin-top:20px;font-weight:bold}.liuli-field__hint{margin:8px;color:#555}.liuli-mode-row{display:flex;justify-content:space-between;margin:8px 0}</style><div id="settings"></div>');
    await settings.addStyleTag({ content: css });
    await settings.addScriptTag({ content: source });
    await settings.evaluate(() => LiuliLayout.buildLayoutControls(document.querySelector('#settings')));
    await settings.waitForFunction(() => document.querySelectorAll('.liuli-lo-icon.has-icon').length === 11);
    assert.equal(await settings.locator('.liuli-lo-list[data-icon-kind="menu"] .liuli-lo-grip').count(), 4);
    assert.equal(await settings.locator('button[title="上移"],button[title="下移"]').count(), 0);
    assert.equal(await settings.locator('.liuli-lo-list[data-icon-kind="menu"] [data-order-key="复读"] .liuli-lo-icon path').count(), 2);
    assert.equal(await settings.locator('.liuli-lo-list[data-icon-kind="bar"] [data-order-key="截图"] use').evaluate(node => node.getAttribute('xlink:href')), '/_upper_/resource/icons/screenshot.svg#screenshot');
    report.checks.push('Original menu, input-toolbar and navigation icons reach the separate settings window; repeat uses +1 bubble.');
    await settings.evaluate(() => {
      window.dragEvents = [];
      for (const type of ['dragstart', 'drop']) document.addEventListener(type, event => window.dragEvents.push({ type, trusted: event.isTrusted }), true);
    });
    const menuList = settings.locator('.liuli-lo-list[data-icon-kind="menu"]');
    await menuList.locator('[data-order-key="收藏"]').dragTo(menuList.locator('[data-order-key="复制"]'), { targetPosition: { x: 100, y: 4 } });
    assert.deepEqual((await config(settings)).menuOrder, ['收藏', '复制', '转发', '复读']);
    assert.deepEqual(await names(settings, 'menu'), ['收藏', '复制', '转发', '复读']);
    assert((await settings.evaluate(() => window.dragEvents)).every(event => event.trusted));
    await main.waitForFunction(() => document.querySelector('.q-context-menu-item').style.order === '1');
    report.checks.push('Trusted browser drag persists order and updates native menu CSS order across windows.');
    await menuList.locator('[data-order-key="收藏"] .liuli-lo-grip').focus();
    await settings.keyboard.press('ArrowDown');
    assert.deepEqual((await config(settings)).menuOrder, ['复制', '收藏', '转发', '复读']);
    assert.equal(await settings.evaluate(() => document.activeElement.closest('.liuli-lo-row')?.dataset.orderKey), '收藏');
    assert.match(await settings.locator('[role="status"]').first().textContent(), /第 2 项/);
    report.checks.push('Arrow keys reorder with focus retained and announce the new position.');
    const barList = settings.locator('.liuli-lo-list[data-icon-kind="bar"]');
    await barList.locator('[data-order-key="截图"]').dragTo(barList.locator('[data-order-key="表情"]'), { targetPosition: { x: 100, y: 4 } });
    assert.deepEqual((await config(settings)).barOrder, ['截图', '表情', '图片', '文件']);
    assert.equal((await config(settings)).barPinned, 2);
    assert.equal(await barList.locator('.liuli-lo-divider').evaluate(node => [...node.parentElement.children].filter(child => child.classList.contains('liuli-lo-row')).indexOf(node.nextElementSibling)), 2);
    await main.waitForFunction(() => [...document.querySelectorAll('.bar-icon.liuli-pinned .icon-item')].map(node => node.getAttribute('aria-label')).sort().join(',') === '截图,表情');
    report.checks.push('Dragging across the input/More divider swaps membership while preserving the button count.');
    const beforeCancel = JSON.stringify(await config(settings));
    const from = await menuList.locator('[data-order-key="复制"]').boundingBox();
    const to = await menuList.locator('[data-order-key="复读"]').boundingBox();
    await settings.mouse.move(from.x + 40, from.y + 14);
    await settings.mouse.down();
    await settings.mouse.move(to.x + 40, to.y + 20, { steps: 8 });
    await settings.keyboard.press('Escape');
    await settings.mouse.up();
    assert.equal(JSON.stringify(await config(settings)), beforeCancel);
    assert.equal(await settings.locator('.is-dragging,.is-drop-before,.is-drop-after').count(), 0);
    report.checks.push('Cancelling a drag leaves saved order and visual state intact.');
    await main.evaluate(() => {
      const original = document.querySelector('.q-context-menu-item__icon svg');
      original.innerHTML = '<path d="M1 1h20v20H1z" onclick="window.badIcon=1"/><foreignObject><div>bad</div></foreignObject><use href="https://example.invalid/bad.svg#x"/>';
      LiuliLayout.applyMenu(document.querySelector('.aio-right-click-menu'));
    });
    await settings.waitForFunction(() => document.querySelector('.liuli-lo-list[data-icon-kind="menu"] [data-order-key="复制"] .liuli-lo-icon path')?.getAttribute('d') === 'M1 1h20v20H1z');
    assert.equal(await settings.locator('.liuli-lo-icon [onclick],.liuli-lo-icon foreignObject,.liuli-lo-icon [href^="https:"]').count(), 0);
    assert.equal(await main.evaluate(() => document.querySelector('.bar-icon svg') === window.originalSvg), true);
    await settings.locator('.liuli-lo-list[data-icon-kind="menu"] [data-order-key="复制"] .liuli-lo-icon').click();
    assert.equal(await main.evaluate(() => window.nativeClicks), 0);
    report.checks.push('Stored icons refresh across windows, strip executable/remote markup, and retain native nodes and handlers.');
    await main.locator('.q-context-menu-item').first().click();
    assert.equal(await main.evaluate(() => window.nativeClicks), 1);
    const beforeRebuild = JSON.stringify(await config(settings));
    await settings.evaluate(() => { document.querySelector('#settings').innerHTML = ''; LiuliLayout.buildLayoutControls(document.querySelector('#settings')); });
    assert.equal(JSON.stringify(await config(settings)), beforeRebuild);
    assert.deepEqual(await names(settings, 'menu'), ['复制', '收藏', '转发', '复读']);
    assert.equal(await settings.locator('.liuli-lo-icon.has-icon').count(), 11);
    await settings.screenshot({ path: path.join(output, 'sortable-settings.png'), fullPage: true });
    report.checks.push('Rebuilding settings preserves ordering and cached original icons without writing layout settings.');
    report.dragEvents = await settings.evaluate(() => window.dragEvents);
    report.passed = true;
  } catch (error) { report.error = error.stack; process.exitCode = 1; }
  finally { await browser.close(); fs.writeFileSync(path.join(output, 'report.json'), JSON.stringify(report, null, 2)); console.log(JSON.stringify(report, null, 2)); }
})();
